import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';
import { format } from 'prettier';

const root = process.cwd();
const source = path.join(root, 'resources/images/logokabinet.png');
const output = path.join(root, 'resources/svelte/lib/logokabinet-ascii.js');
const characters = ' .,:;irsXA253hMHGS#9B&@';

const escapeHtml = (value) => value
  .replaceAll('&', '&amp;')
  .replaceAll('<', '&lt;')
  .replaceAll('>', '&gt;')
  .replaceAll('"', '&quot;')
  .replaceAll("'", '&#39;');

const brightenChannel = (value) => Math.max(0, Math.min(255, Math.round((value * 1.22) + 14)));

async function generateAscii() {
  const image = sharp(source);
  const metadata = await image.metadata();
  const targetWidth = 64;
  const targetHeight = Math.max(1, Math.round((metadata.height / metadata.width) * targetWidth * 0.5 * 1.25));

  const { data, info } = await image
    .resize(targetWidth, targetHeight)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true });

  const { width, height } = info;
  const charsCount = characters.length;
  
  let html = '';
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = (width * y + x) * 4;
      const r = data[idx];
      const g = data[idx + 1];
      const b = data[idx + 2];
      const a = data[idx + 3];

      if (a < 128) {
        html += ' ';
        continue;
      }

      const gray = 0.299 * r + 0.587 * g + 0.114 * b;
      // Reverse index mapping depending on if characters are light-to-dark or dark-to-light
      // image-to-ascii characters: ' .,:;irsXA253hMHGS#9B&@' (darkest to lightest? usually space is lightest)
      const charIndex = Math.floor((gray / 255) * (charsCount - 1));
      // Usually darker pixels get denser characters.
      // Let's assume the string is from lightest to darkest.
      // So high gray (white, 255) -> lightest character.
      // low gray (black, 0) -> darkest character.
      // Let's use: (charsCount - 1) - charIndex so 255 maps to ' ' and 0 maps to '@'
      const char = characters[(charsCount - 1) - charIndex] || characters[0];

      if (char === ' ') {
        html += ' ';
      } else {
        const br = brightenChannel(r);
        const bg = brightenChannel(g);
        const bb = brightenChannel(b);
        html += `<span style="color:rgb(${br},${bg},${bb})">${escapeHtml(char)}</span>`;
      }
    }
    html += '\n';
  }
  
  return html.trimEnd();
}

const ascii = await generateAscii();

const fileContents = await format(
  `// Generated by scripts/generate-logokabinet-ascii.mjs using sharp.\nexport const logokabinetAscii = ${JSON.stringify(ascii)};\n`,
  { parser: 'babel' },
);

await fs.writeFile(output, fileContents, 'utf8');
